import { z } from 'zod';

export const TaskSchema = z.object({
  id: z.string().min(1, "ID is required"),
  projectCode: z.string().min(1, "Project code is required"),
  projectYear: z.union([z.number(), z.string()]).optional(),
  projectStore: z.string().optional(),
  name: z.string().min(1, "Name is required").max(500, "Name exceeds max length"),
  start: z.string(),
  baselineStart: z.string().optional(),
  baselineFinish: z.string().optional(),
  finish: z.string(),
  duration: z.string().optional(),
  durationManual: z.boolean().optional(),
  finishManual: z.boolean().optional(),
  approval: z.string().optional(),
  approvedAt: z.string().nullable().optional(),
  realtimeUpdate: z.boolean().optional(),
  startManual: z.boolean().optional(),
  party: z.string().optional(),
  delegation: z.boolean().optional(),
  predecessor: z.string().optional(),
  notes: z.array(z.any()).optional(),
  runningStatus: z.enum(['On process', 'Delayed', 'Completed', 'Upcoming']).optional().or(z.string()),
  isShared: z.boolean().optional(),
  updatedAt: z.string().optional(),
  orderIndex: z.number().optional(),
  comments: z.array(z.any()).optional(),
  textColor: z.string().optional(),
  taskCodePhu: z.string().optional(),
  parentTaskId: z.string().optional(),
  isDeleted: z.boolean().optional()
}).passthrough();

export const ProjectSchema = z.object({
  id: z.string().optional(),
  no: z.number(),
  store: z.string(),
  year: z.union([z.number(), z.string()]),
  code: z.string().min(1, "Code is required"),
  name: z.string().min(1, "Name is required"),
  detail: z.string().optional(),
  party: z.string().optional(),
  start: z.string().optional(),
  baselineStart: z.string().optional(),
  baselineFinish: z.string().optional(),
  handover: z.string().optional(),
  opening: z.string().optional(),
  startMode: z.enum(['auto', 'manual']).optional(),
  handoverMode: z.enum(['auto', 'manual']).optional(),
  openingMode: z.enum(['auto', 'manual']).optional(),
  budget: z.number().min(0, "Budget cannot be negative").optional(),
  actual: z.number().min(0).optional(),
  location: z.string().optional(),
  type: z.string().optional(),
  note: z.string().optional(),
  supportingFee: z.number().min(0).optional(),
  computedTakStart: z.string().optional(),
  computedTakCompl: z.string().optional(),
  computedOpening: z.string().optional(),
  computedStatus: z.string().optional(),
  computedPlanProgress: z.number().min(0).max(100).optional(),
  computedActProgress: z.number().min(0).max(100).optional(),
  taskSummaries: z.array(z.any()).optional(),
  realtimeUpdate: z.boolean().optional(),
  delegation: z.boolean().optional(),
  updatedAt: z.string().optional(),
  textColor: z.string().optional(),
  comments: z.array(z.any()).optional(),
  mdStatus: z.string().optional(),
  isPinned: z.boolean().optional(),
  pinnedOrder: z.number().optional(),
  parentId: z.string().optional(),
  financial: z.any().optional(),
  isDeleted: z.boolean().optional()
}).passthrough();

export const CostSchema = z.object({
  id: z.string().min(1, "ID is required"),
  projectCode: z.string().min(1, "Project code is required"),
  projectYear: z.union([z.number(), z.string()]).optional(),
  projectStore: z.string().optional(),
  amount: z.number().optional(),
  approvedAmount: z.number().optional(),
  actual: z.number().min(0, "Actual cost cannot be negative").default(0),
  costType: z.enum(['act', 'forc']).optional().or(z.string()),
  firstPaid: z.number().min(0).optional(),
  firstPaidAt: z.string().optional(),
  firstStatus: z.string().optional(),
  secondPaid: z.number().min(0).optional(),
  secondPaidAt: z.string().optional(),
  secondStatus: z.string().optional(),
  thirdPaid: z.number().min(0).optional(),
  thirdPaidAt: z.string().optional(),
  thirdStatus: z.string().optional(),
  advanceAmount: z.number().min(0).optional(),
  isDeleted: z.boolean().optional()
}).passthrough();
